#!/usr/bin/env python3
"""Render public/ from src/index.template.html.

- Inlines the PrimorDecode wordmark (brand/logo/wordmark.svg) into the header
  and footer, giving each copy unique ids (two inline SVGs on one page must not
  share mask ids).
- Writes /news/ as a placeholder page sharing the homepage's header, styles
  and footer.
- Writes /benchmark/ as a full page (src/benchmark.template.html +
  src/benchmark.css + src/benchmark.js) that reads its data from
  public/benchmark/data/*.json, generated by
  omicos-terminal-bench-science/scripts/export_site_bench.py. Still shares
  the homepage's header, styles and footer.

Usage: python3 build.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SVG = (ROOT / "brand/logo/wordmark.svg").read_text()
TPL = (ROOT / "src/index.template.html").read_text()


def logo(suffix: str) -> str:
    s = re.sub(r"<title>.*?</title>", "", SVG)
    for old in sorted(set(re.findall(r'id="([^"]+)"', s))):
        s = s.replace(f'id="{old}"', f'id="{old}-{suffix}"').replace(f"url(#{old})", f"url(#{old}-{suffix})")
    return s.replace("<svg ", '<svg aria-hidden="true" focusable="false" ', 1)


VIS = (ROOT / "src/visuals.js").read_text().replace("{{EMBRYO_B64}}", (ROOT / "src/embryo_points.b64").read_text().strip())
home = TPL.replace("{{LOGO_HEADER}}", logo("h")).replace("{{LOGO_FOOTER}}", logo("f")).replace("{{VISUALS_JS}}", VIS)
out = ROOT / "public"
out.mkdir(exist_ok=True)
(out / "index.html").write_text(home)

STUB_MAIN = """<main>
  <section class="hero" style="padding-bottom:160px">
    <div class="wrap">
      <span class="pill"><span class="tag">Soon</span><span class="muted">{kicker}</span></span>
      <h1>{title}</h1>
      <p class="lede">{lede}</p>
      <div class="cta"><a class="btn btn-light btn-hero" href="/">Back to home</a></div>
    </div>
  </section>
</main>"""

pages = {
    "news": dict(
        title="News",
        kicker="Updates from ScienceInfra",
        lede="Releases and research updates from the verse family will be posted here.",
    ),
}
for slug, p in pages.items():
    html = re.sub(r"<main>.*?</main>", STUB_MAIN.format(**p), home, flags=re.S)
    html = html.replace("<title>ScienceInfra</title>", f"<title>{p['title']} · ScienceInfra</title>")
    html = html.replace('href="#verses"', 'href="/#verses"')
    # The stub has no #field/#orb canvases or card loops; drop the page script.
    html = re.sub(r"<script>.*</script>", lambda m: "<script>(()=>{const h=document.getElementById('hdr');const f=()=>h.classList.toggle('scrolled',scrollY>8);addEventListener('scroll',f,{passive:true});f()})()</script>", html, flags=re.S)
    d = out / slug
    d.mkdir(exist_ok=True)
    (d / "index.html").write_text(html)

# /benchmark/: a full page (not a placeholder stub). Markup, styles and JS
# come from src/benchmark.*; the page fetches its numbers at runtime from
# public/benchmark/data/*.json (generated by the TBS harness's
# scripts/export_site_bench.py -- this build step never touches that data).
BENCH_MAIN = (ROOT / "src/benchmark.template.html").read_text()
BENCH_CSS = (ROOT / "src/benchmark.css").read_text()
BENCH_JS = (ROOT / "src/benchmark.js").read_text()
bench_html = re.sub(r"<main>.*?</main>", BENCH_MAIN.strip(), home, flags=re.S)
bench_html = bench_html.replace("<title>ScienceInfra</title>", "<title>Benchmark · ScienceInfra</title>")
bench_html = bench_html.replace(
    "content=\"ScienceInfra builds open analysis libraries that AI agents look up and call — omicverse, matverse, socialverse, physverse and astroverse.\"",
    "content=\"Benchmark results for the ScienceInfra verse libraries on Terminal-Bench-Science and our blind held-out research tasks.\"",
)
bench_html = bench_html.replace("</style>", f"{BENCH_CSS}\n</style>", 1)
# The homepage's two scripts (typed headline + visuals.js) are replaced wholesale
# by the benchmark page's own script (header-scroll + the dropdown/tabs/fetch logic).
bench_html = re.sub(r"<script>.*</script>", lambda m: f"<script>\n{BENCH_JS}</script>", bench_html, flags=re.S)
bench_dir = out / "benchmark"
bench_dir.mkdir(exist_ok=True)
(bench_dir / "data").mkdir(exist_ok=True)
(bench_dir / "index.html").write_text(bench_html)

print("built:", ", ".join(str(p.relative_to(ROOT)) for p in sorted(out.rglob("*.html"))))
